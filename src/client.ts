/**
 * `@orpc/tanstack-query` attaches this symbol to every call's client context
 * so interceptors see the query key and operation type. Reading it directly
 * keeps TanStack Query calls batched without importing `@orpc/tanstack-query`.
 */
const TANSTACK_OPERATION_CONTEXT = Symbol.for(
	'ORPC_TANSTACK_QUERY_OPERATION_CONTEXT'
)

/** `query`, `infinite`, `mutation`, `streamed` or `live`; undefined for a direct `client.x()` call. */
function tanstackOperationType(context: object): unknown {
	const op = (context as Record<symbol, unknown>)[TANSTACK_OPERATION_CONTEXT]
	if (typeof op !== 'object' || op === null) return undefined
	return (op as { type?: unknown }).type
}

function isTanstackStream(context: object): boolean {
	const type = tanstackOperationType(context)
	return type === 'live' || type === 'streamed'
}

function isTanstackQuery(context: object): boolean {
	const type = tanstackOperationType(context)
	return type === 'query' || type === 'infinite'
}

function hasCustomContext(context: object): boolean {
	if (Object.keys(context).length > 0) return true
	for (const symbol of Object.getOwnPropertySymbols(context)) {
		if (symbol !== TANSTACK_OPERATION_CONTEXT) return true
	}
	return false
}

type BatchOptions<T extends ClientContext> = ConstructorParameters<
	typeof BatchLinkPlugin<T>
>[0]

export type CreateRpcLinkOptions<T extends ClientContext> = Omit<
	RPCLinkOptions<T>,
	'url'
> & {
	/**
	 * The handler's path, e.g. `'/rpc'` (the host goes in `origin`). Any
	 * `string` is accepted, checked to start with `/` when the link is made,
	 * so a path constant needs no `as const`. A function form is passed on.
	 */
	url?: RPCLinkOptions<T>['url'] | string
	/**
	 * Client-safe manifest generated by createStreamManifest(router). Calls
	 * opened by the framework helpers, or with `context: streamCall`, are
	 * recognised without it.
	 */
	streamPaths?: readonly (readonly string[])[]
	/**
	 * Collapse parallel calls into one HTTP request, matching `mountOrpc`'s
	 * server-side batching. Default: true (25 calls). Pass false to turn off.
	 *
	 * A batch is one HTTP request, so it carries one client context. By
	 * default only calls without a client context are batched; pass
	 * `groups` to batch calls that share a context (e.g. a token).
	 */
	batch?:
		| boolean
		| {
				maxSize?: number
				/**
				 * How the server answers a batch. `'streaming'` (default) sends each
				 * result as it finishes, so a fast call does not wait behind a slow
				 * one. `'buffered'` answers once, with every result as one JSON
				 * array: for a host or proxy that buffers the response anyway.
				 */
				mode?: 'streaming' | 'buffered'
				/**
				 * `'queries'` batches only calls made through TanStack Query as a
				 * query (`queryOptions`, `infiniteOptions`, `fetchQuery`); mutations
				 * and direct `client.x()` calls are sent on their own. Default:
				 * every call.
				 */
				only?: 'queries'
				/** Calls that must not be batched. Default: {@link isSubscriptionPath}. */
				exclude?: (path: readonly string[]) => boolean
				groups?: BatchOptions<T>['groups']
		  }
}

/**
 * Streaming responses cannot be batched, and the request does not say a
 * response will stream - so streaming routes are recognised by name. The
 * default treats any path segment containing `subscribe` as one (the
 * convention `fnLive` routers use: `{ list, subscribe }`).
 */
export const isSubscriptionPath = (path: readonly string[]) =>
	path.some((segment) => segment.toLowerCase().includes('subscribe'))

/**
 * `url` checked to be a path, the shape oRPC 2's `StandardUrl` type asks
 * for; a full URL there would otherwise fail only per request.
 */
function pathUrl(url: string): StandardUrl {
	if (/^[a-z][a-z\d+.-]*:/i.test(url)) {
		let hint =
			"pass origin (e.g. 'https://api.example.com') and a path url (e.g. '/rpc')"
		try {
			const parsed = new URL(url)
			hint = `pass origin: '${parsed.origin}' and url: '${parsed.pathname}${parsed.search}'`
		} catch {
			/* Keep the generic hint when the scheme-prefixed string is not a valid URL. */
		}
		throw new TypeError(`orpc-fn: RPCLink url is a path since oRPC 2; ${hint}`)
	}
	if (!url.startsWith('/'))
		throw new TypeError(
			`orpc-fn: RPCLink url must be a path starting with '/', got '${url}'`
		)
	return url as StandardUrl
}

/**
 * `RPCLink` with request batching: a page-load burst becomes one request
 * instead of many queued on the server's event loop.
 *
 * ```ts
 * const client: RouterClient<typeof router> = createORPCClient(
 *   createRpcLink({ origin: 'https://api.example.com', url: '/rpc' })
 * )
 * export const orpc = createTanstackQueryUtils(client)
 * ```
 */
export function createRpcLink<T extends ClientContext = ClientContext>(
	options: CreateRpcLinkOptions<T>
): RPCLink<T> {
	const { batch = true, plugins = [], streamPaths, url, ...link } = options
	const rest: RPCLinkOptions<T> = {
		...link,
		...(url === undefined
			? {}
			: { url: typeof url === 'string' ? pathUrl(url) : url })
	}
	const streams = new Set(streamPaths?.map((path) => JSON.stringify(path)))
	if (batch === false) return new RPCLink<T>({ ...rest, plugins })
	const {
		maxSize = 25,
		mode = 'streaming',
		only,
		exclude = isSubscriptionPath,
		groups
	} = batch === true ? {} : batch
	if (mode !== 'streaming' && mode !== 'buffered')
		throw new TypeError(
			`orpc-fn: batch.mode must be 'streaming' or 'buffered', got '${String(mode)}'`
		)
	if (only !== undefined && only !== 'queries')
		throw new TypeError(
			`orpc-fn: batch.only must be 'queries', got '${String(only)}'`
		)
	return new RPCLink<T>({
		...rest,
		plugins: [
			new BatchLinkPlugin<T>({
				maxSize,
				// Streaming unless asked: each result is sent as it finishes, so a
				// fast call does not wait behind a slow one (oRPC 2's own default
				// buffers the whole batch).
				mode,
				groups: groups ?? [
					// Only context-free calls reach this group (see `filter` below),
					// so the batch's empty context is exactly theirs.
					{ condition: () => true, context: {} as T }
				],
				filter: ({ path, context }) =>
					!(
						isStreamCall(context) ||
						isTanstackStream(context) ||
						(streams.size > 0 && streams.has(JSON.stringify(path))) ||
						exclude(path) ||
						(only === 'queries' && !isTanstackQuery(context)) ||
						(groups === undefined && hasCustomContext(context))
					)
			}),
			...plugins
		]
	})
}

/**
 * The procedure or router path in a TanStack Query key from
 * `@orpc/tanstack-query`, which oRPC 2 starts with the path, or with a
 * `prefix` and then the path: `operationPath(orpc.order.get.key())` is
 * `['order', 'get']`.
 */
export function operationPath(
	key:
		| readonly [path: readonly string[], options: unknown]
		| readonly [prefix: string, path: readonly string[], options: unknown]
): readonly string[] {
	return key.length === 3 ? key[1] : key[0]
}

/**
 * Typed check for a route error on the client. The RPC link rebuilds thrown
 * route errors as `ORPCError`, so `instanceof` plus `code` is the contract.
 */
export function hasOrpcErrorCode<TCode extends ORPCErrorCode>(
	error: unknown,
	code: TCode
): error is ORPCError<TCode, unknown> {
	return error instanceof ORPCError && error.code === code
}

/**
 * The HTTP status a failed call got, or `undefined` when no response arrived
 * (network failure, abort). oRPC 2's `ORPCError` has no `status`: the link
 * keeps the response on the error's `cause`. A response that is not oRPC's,
 * such as a proxy's 502 page, throws `MalformedResponseError`, which carries
 * it too. The client half of the server's `errorStatusOf`.
 *
 * ```ts
 * onError: (error) => recordFailure({ status: responseStatusOf(error) })
 * ```
 */
export function responseStatusOf(error: unknown): number | undefined {
	const response =
		error instanceof ResponseError
			? error
			: error instanceof ORPCError && error.cause instanceof ResponseError
				? error.cause
				: undefined
	return response?.response.status
}

/**
 * The server's message, only when the backend marked it user-safe by putting
 * a `userMessage` string on the error's `data`. Route error messages are
 * developer text (English, internal model names), so they are not shown by
 * default; they stay on the error for logs and error tracking.
 *
 * ```ts
 * throw new ORPCError('BAD_REQUEST', {
 *   message: 'Deal has no pipeline stage',       // logs, telemetry
 *   data: { userMessage: 'Choose a stage first.' } // the user reads this
 * })
 * ```
 */
export function userSafeServerMessage(error: unknown): string | null {
	if (!(error instanceof ORPCError)) return null
	const data: unknown = error.data
	if (typeof data !== 'object' || data === null) return null
	const userMessage = (data as { userMessage?: unknown }).userMessage
	return typeof userMessage === 'string' && userMessage.trim().length > 0
		? userMessage
		: null
}

/** User-facing text for a caught error: the opted-in server message, else your localized fallback. */
export function userFacingErrorMessage(
	error: unknown,
	fallback: string
): string {
	return userSafeServerMessage(error) ?? fallback
}

/**
 * Like {@link userFacingErrorMessage}, but a rejected input lists its
 * fields: the server's `userMessage`, else one `path: message` line per
 * validation issue of a BAD_REQUEST, else your fallback.
 */
export function formatClientError(error: unknown, fallback: string): string {
	const safe = userSafeServerMessage(error)
	if (safe) return safe
	if (error instanceof ORPCError && error.code === 'BAD_REQUEST') {
		const issues = issuesOf(error)
		if (issues.length > 0) return issues.map(formatIssue).join('\n')
	}
	return fallback
}

/**
 * `serialize`/`deserialize` for a TanStack Query persister. API payloads carry
 * `Date`s (and maybe `Map`s, `Set`s, `BigInt`s) that plain JSON returns as
 * strings; oRPC's own serializer round-trips them. Caches persisted under
 * oRPC 1 still restore.
 *
 * ```ts
 * createAsyncStoragePersister({ storage: AsyncStorage, ...queryCacheSerializer })
 * ```
 */
export const queryCacheSerializer = {
	serialize(value: unknown): string {
		const { json, meta } = rpcJson.serializeJson(value)
		return JSON.stringify({ json, meta: meta ?? [] })
	},
	deserialize<T>(text: string): T {
		const { json, meta } = JSON.parse(text) as { json: unknown; meta: unknown }
		return rpcJson.deserializeJson({ json, meta: normalizeMeta(meta) }) as T
	}
}
