import type { RouterContract } from '@orpc/contract'
import {
	type AnyRouter,
	type AnyProcedure,
	walkProcedureContractsAsync,
	walkProcedureContractsSync
} from '@orpc/server'
import { isProcedure } from './compatibility.js'
import { readFnMeta } from './meta.js'

/**
 * Creates a router object from routes or nested routers.
 * Simply returns the routes as a const object for type inference.
 *
 * @example
 * ```ts
 * const items = createRouter({ getItem, updateItem })
 * export const api = createRouter({ metabase, items })
 * ```
 */
export function createRouter<T extends AnyRouter>(routes: T): Readonly<T> {
	return routes
}

/**
 * Calls `callback` with every procedure in `router` and its path, skipping
 * contract-only entries: a tool catalog or a route audit reads each route
 * with `readFnMeta(procedure)`. Resolve lazy routers first with oRPC's
 * `unlazyRouter`.
 *
 * ```ts
 * walkProcedures(router, (procedure, path) => {
 *   const { name } = readFnMeta(procedure)
 *   if (name) byName.set(name, procedure)
 * })
 * ```
 */
export function walkProcedures(
	router: AnyRouter | RouterContract,
	callback: (procedure: AnyProcedure, path: readonly string[]) => void
): void {
	const unresolved = walkProcedureContractsSync(router, (entry, path) => {
		if (isProcedure(entry)) callback(entry, path)
	})
	if (unresolved.length)
		throw new TypeError(
			'orpc-fn: resolve lazy routers with unlazyRouter before walkProcedures'
		)
}

/** Serialize these paths to a frontend module; this helper belongs on the server. */
export function createStreamManifest(
	router: AnyRouter
): readonly (readonly string[])[] {
	const paths: string[][] = []
	const unresolved = walkProcedureContractsSync(router, (contract, path) => {
		if (readFnMeta(contract as AnyProcedure).stream) paths.push([...path])
	})
	if (unresolved.length)
		throw new TypeError(
			'orpc-fn: lazy routers require createStreamManifestAsync'
		)
	return paths
}

/** Resolve lazy routers before generating the same serializable path manifest. */
export async function createStreamManifestAsync(
	router: AnyRouter
): Promise<readonly (readonly string[])[]> {
	const paths: string[][] = []
	await walkProcedureContractsAsync(router, (contract, path) => {
		if (readFnMeta(contract as AnyProcedure).stream) paths.push([...path])
	})
	return paths
}

const JS_IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

/**
 * Deterministic module source for a stream manifest: paths sorted, `json`
 * as an array, `ts` as `export const <name>`. Used by `orpc-fn stream-manifest`.
 */
export function renderStreamManifest(
	paths: readonly (readonly string[])[],
	options: { format: 'json' | 'ts'; name?: string | undefined }
): string {
	const lines = paths
		.map(
			(path) =>
				`\t[${path.map((segment) => JSON.stringify(segment)).join(', ')}]`
		)
		.sort()
	const array = lines.length ? `[\n${lines.join(',\n')}\n]` : '[]'
	if (options.format === 'json') return `${array}\n`
	const exportName = options.name ?? 'streamPaths'
	if (!JS_IDENTIFIER.test(exportName))
		throw new TypeError(
			`orpc-fn: stream manifest export name "${exportName}" must be a valid JavaScript identifier`
		)
	return `// Generated by \`orpc-fn stream-manifest\`. Do not edit.\nexport const ${exportName}: readonly (readonly string[])[] = ${array}\n`
}
