import { expect, test } from 'bun:test'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const cli = new URL('./cli.ts', import.meta.url).pathname
const fixture = new URL('../tests/fixture.ts', import.meta.url).pathname

function run(cwd: string, ...args: string[]) {
	const result = Bun.spawnSync(['bun', cli, ...args], { cwd })
	return {
		code: result.exitCode,
		stdout: result.stdout.toString(),
		stderr: result.stderr.toString()
	}
}

test('help lists the stream-manifest command and its options', () => {
	expect(run('.', '--help')).toEqual({
		code: 0,
		stdout: `orpc-fn

Usage: orpc-fn <command> [options]

Commands:
  stream-manifest        Generate the stream manifest for createRpcLink({ streamPaths })
  completion <bash|zsh>  Print a shell completion script

Options:
  -h, --help  Show help

Run "orpc-fn <command> --help" for a command's options.
`,
		stderr: ''
	})
	expect(run('.', 'stream-manifest', '--help')).toEqual({
		code: 0,
		stdout: `Usage: orpc-fn stream-manifest <module> [options]

Generate the stream manifest for createRpcLink({ streamPaths })

Imports the router (export "default" unless #export is given) and writes the
paths of its streaming routes for createRpcLink({ streamPaths }). The file is
only written when its content changes. --check writes nothing and exits 1 when
the file is missing or stale. Importing the router runs its module code; run
TypeScript routers with a runtime that loads .ts (bun, tsx, node >= 22.18).

Arguments:
  <module>  Router module, with #export for a named export

Options:
  --out <string>   Manifest to write: file.ts or file.json
  --name <string>  Exported constant name in a .ts file
  --check          Exit 1 when the file is missing or stale
  -h, --help       Show help
`,
		stderr: ''
	})
	expect(run('.').code).toBe(2)
	expect(run('.', 'stream-manifest', 'router.ts')).toEqual({
		code: 2,
		stdout: '',
		stderr: `--out: Invalid input: expected string, received undefined
Run "orpc-fn stream-manifest --help" for usage.
`
	})
})

test('stream-manifest writes deterministic modules, resolves lazy routers and checks staleness', () => {
	// Inside the repo so the router resolves the same @orpc/server copy.
	const dir = mkdtempSync(new URL('../.cli-test-', import.meta.url).pathname)
	try {
		writeFileSync(
			join(dir, 'router.ts'),
			`import { lazy } from '@orpc/server'
import { z } from 'zod'
import { fn, fnLive } from ${JSON.stringify(fixture)}
const feed = fnLive({
	name: 'feed',
	procedure: 'public',
	input: z.object({}),
	handler: () => 1,
	live: { eventSchema: z.object({}), channel: 'feed' }
})
const ping = fn({ name: 'ping', procedure: 'public', handler: () => 'pong' })
export const api = {
	ping,
	"it's": { subscribe: feed.subscribe },
	lazyFeed: lazy(async () => ({ default: { list: feed.procedure, watch: feed.subscribe } })),
	a: { subscribe: feed.subscribe }
}
// Open handle the CLI must not wait for.
setInterval(() => {}, 1000)
`
		)
		expect(
			run(dir, 'stream-manifest', 'router.ts#api', '--out', 'paths.ts')
		).toEqual({ code: 0, stdout: 'orpc-fn: wrote paths.ts\n', stderr: '' })
		expect(readFileSync(join(dir, 'paths.ts'), 'utf8')).toBe(
			`// Generated by \`orpc-fn stream-manifest\`. Do not edit.
export const streamPaths: readonly (readonly string[])[] = [
\t["a", "subscribe"],
\t["it's", "subscribe"],
\t["lazyFeed", "watch"]
]
`
		)
		expect(
			run(
				dir,
				'stream-manifest',
				'router.ts#api',
				'--out',
				'paths.ts',
				'--check'
			).code
		).toBe(0)

		writeFileSync(join(dir, 'paths.ts'), 'stale')
		const stale = run(
			dir,
			'stream-manifest',
			'router.ts#api',
			'--out',
			'paths.ts',
			'--check'
		)
		expect(stale.code).toBe(1)
		expect(stale.stderr).toBe(
			'orpc-fn: paths.ts is stale; rerun without --check to update it\n'
		)
		expect(readFileSync(join(dir, 'paths.ts'), 'utf8')).toBe('stale')

		expect(
			run(dir, 'stream-manifest', 'router.ts#api', '--out', 'paths.json').code
		).toBe(0)
		expect(JSON.parse(readFileSync(join(dir, 'paths.json'), 'utf8'))).toEqual([
			['a', 'subscribe'],
			["it's", 'subscribe'],
			['lazyFeed', 'watch']
		])
		expect(
			run(dir, 'stream-manifest', 'router.ts#missing', '--out', 'x.ts')
		).toEqual({
			code: 2,
			stdout: '',
			stderr: 'orpc-fn: router.ts has no router export "missing"\n'
		})
	} finally {
		rmSync(dir, { recursive: true, force: true })
	}
})
